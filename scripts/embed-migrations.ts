// Bundles prisma/migrations/*/migration.sql into a TS module so the embedded
// database (lib/db.ts) can apply them on any host without filesystem access.
// Runs on postinstall and before build.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "prisma", "migrations");
const migrations = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(dir, d.name, "migration.sql")))
  .map((d) => d.name)
  .sort()
  .map((name) => ({ name, sql: readFileSync(join(dir, name, "migration.sql"), "utf8") }));

mkdirSync(join(process.cwd(), "lib", "generated"), { recursive: true });
writeFileSync(
  join(process.cwd(), "lib", "generated", "migrations.ts"),
  `// Generated by scripts/embed-migrations.ts — do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(migrations, null, 2)};\n`
);
console.log(`Embedded ${migrations.length} migration(s).`);
